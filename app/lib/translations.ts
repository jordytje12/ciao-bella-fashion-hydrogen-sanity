export type UiTranslations = (typeof UI_TRANSLATIONS)[keyof typeof UI_TRANSLATIONS];

export function getUiTranslations(language?: LanguageCode | null): UiTranslations {
  return UI_TRANSLATIONS[language as keyof typeof UI_TRANSLATIONS] ?? UI_TRANSLATIONS.NL;
}

export function t(
  template: string,
  vars: Record<string, string | number>,
): string {
  return Object.entries(vars).reduce(
    (result, [key, value]) => result.replace(`{${key}}`, String(value)),
    template,
  );
}
